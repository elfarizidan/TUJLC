create or replace function tujlc.member_home(m tujlc.members) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare v_per text;
begin
  select nama into v_per from periode order by aktif desc, id desc limit 1;
  return jsonb_build_object(
    'me', public_member(m) || jsonb_build_object('nim', m.nim, 'email', m.email),
    'jadwal', q_rows('select id, judul, tanggal, jam_mulai, jam_selesai, kampus, ruang, bahasa, deskripsi from events
                    where tampil = 1 and tanggal >= $1[1] order by tanggal, jam_mulai limit 20', today()),
    'kampus', kampus(),
    'pengurus', q_rows('select p.nama, p.nim, p.jabatan, p.divisi, p.periode, coalesce(f.data, p.foto) as foto
                      from pengurus p left join fotos f on f.key = p.foto where p.periode = $1[1] order by p.urut, p.nama', coalesce(v_per, '')),
    'periode', coalesce(v_per, ''),
    'periode_list', coalesce((select jsonb_agg(nama order by id desc) from periode), '[]'),
    'kelas_saya', q_rows('select * from kelas_daftar where member_id = $1[1]::bigint order by id desc', m.id::text),
    'absen_saya', q_rows('select e.judul, e.tanggal, a.status from absensi a join events e on e.id = a.event_id
                        where a.member_id = $1[1]::bigint order by e.tanggal desc limit 20', m.id::text),
    'iuran_saya', q_rows('select bulan, nominal, status from iuran where member_id = $1[1]::bigint order by bulan desc limit 12', m.id::text));
end $$;

create or replace function tujlc.daftar_kelas(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  if coalesce(b->>'bahasa', '') = '' or coalesce(b->>'level', '') = '' then perform err('Pilih bahasa dan level.'); end if;
  if exists (select 1 from kelas_daftar where member_id = m.id and bahasa = b->>'bahasa' and status <> 'ditolak') then
    perform err('Kamu sudah terdaftar di kelas bahasa ini.', 409);
  end if;
  insert into kelas_daftar(member_id, bahasa, level, kampus, jadwal, catatan, created)
    values (m.id, b->>'bahasa', b->>'level', coalesce(b->>'kampus', ''), coalesce(b->>'jadwal', ''), left(coalesce(b->>'catatan', ''), 500), now_iso());
  return '{"ok": true}';
end $$;

create or replace function tujlc.absen_mandiri(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare e events;
begin
  select * into e from events where kode_absen = upper(btrim(coalesce(b->>'kode', ''))) and tanggal = today() limit 1;
  if e.id is null then perform err('Kode absen tidak cocok dengan pertemuan hari ini.', 404); end if;
  insert into absensi(event_id, member_id, status, waktu) values (e.id, m.id, 'hadir', now_iso())
    on conflict (event_id, member_id) do update set status = 'hadir', waktu = excluded.waktu;
  return jsonb_build_object('ok', true, 'judul', e.judul);
end $$;

create or replace function tujlc.add_score(mid bigint, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare s int;
begin
  if coalesce(b->>'game', '') not in ('lari', 'suara', 'susun', 'memori', 'kota', 'duel', 'mabar', 'dunia') then perform err('Game tidak dikenal.'); end if;
  begin s := greatest(0, least(round((b->>'score')::numeric), 1000000))::int; exception when others then s := 0; end;
  insert into scores(member_id, game, lang, score, created) values (mid, b->>'game', coalesce(b->>'lang', ''), s, now_iso());
  return '{"ok": true}';
end $$;

create or replace function tujlc.leaderboard(game text, lang text) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  return jsonb_build_object('top', q_rows(
    'select m.nama, max(s.score) as score from scores s join members m on m.id = s.member_id
      where s.game = $1[1] and ($1[2] = '''' or s.lang = $1[2]) group by s.member_id, m.nama order by score desc limit 10',
    coalesce(game, ''), coalesce(lang, '')));
end $$;

-- ---------------------------------------------------------------------
-- Ruang mabar (2–5 pemain). Disimpan di tabel rooms (dulu di memori server).
-- ---------------------------------------------------------------------
create or replace function tujlc.room_advance(r jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare now_ double precision := epoch(); qs double precision := (r->>'q_start')::double precision;
        over boolean; everyone boolean;
begin
  if r->>'status' <> 'main' then return r; end if;
  over := now_ - qs > (r->>'secs')::int;
  everyone := (select count(*) from jsonb_object_keys(r->'answers')) >= (select count(*) from jsonb_object_keys(r->'players'));
  if (over or everyone) and now_ - qs > 1 then
    if r->'reveal_at' is null or r->'reveal_at' = 'null'::jsonb then
      return jsonb_set(r, '{reveal_at}', to_jsonb(now_));
    end if;
    if now_ - (r->>'reveal_at')::double precision > 3 then  -- tampilkan jawaban 3 detik
      r := r || jsonb_build_object('q', (r->>'q')::int + 1, 'answers', '{}'::jsonb, 'reveal_at', null, 'q_start', now_);
      if (r->>'q')::int >= jsonb_array_length(r->'questions') then r := jsonb_set(r, '{status}', '"selesai"'); end if;
    end if;
  end if;
  return r;
end $$;

create or replace function tujlc.room_state(m tujlc.members, p_code text) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare r jsonb; out jsonb; q jsonb; k text; v jsonb; mid text := m.id::text;
begin
  delete from rooms where created < now() - interval '6 hours';
  select data into r from rooms where code = upper(coalesce(p_code, '')) for update;
  if r is null then perform err('Ruang tidak ditemukan.', 404); end if;
  r := room_advance(r);
  out := jsonb_build_object('code', r->'code', 'status', r->'status', 'lang', r->'lang', 'host', (r->>'host') = mid, 'me', m.id,
    'players', (select coalesce(jsonb_agg(jsonb_build_object('id', key::bigint, 'nama', value->'nama', 'score', value->'score',
                                                             'answered', (r->'answers') ? key)), '[]') from jsonb_each(r->'players')),
    'total', jsonb_array_length(r->'questions'), 'i', r->'q');
  if r->>'status' = 'main' then
    q := r->'questions'->((r->>'q')::int);
    out := out || jsonb_build_object('question', jsonb_build_object('p', q->'p', 'r', q->'r', 'o', q->'o',
              'left', greatest(0, round(((r->>'secs')::numeric - (epoch() - (r->>'q_start')::double precision)::numeric), 1))));
    if r->'reveal_at' is not null and r->'reveal_at' <> 'null'::jsonb then
      out := jsonb_set(out, '{question,c}', q->'c') || jsonb_build_object('reveal', r->'answers');
    end if;
    out := out || jsonb_build_object('my_answer', coalesce(r->'answers'->mid, 'null'::jsonb));
  end if;
  if r->>'status' = 'selesai' and not coalesce((r->>'saved')::boolean, false) then
    r := jsonb_set(r, '{saved}', 'true');
    for k, v in select key, value from jsonb_each(r->'players') loop
      perform add_score(k::bigint, jsonb_build_object('game', 'mabar', 'lang', r->>'lang', 'score', v->'score'));
    end loop;
  end if;
  update rooms set data = r where code = r->>'code';
  return out;
end $$;

create or replace function tujlc.room_create(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare c text;
begin
  loop
    c := tujlc.rand('ABCDEFGHJKLMNPQRSTUVWXYZ', 4);
    exit when not exists (select 1 from rooms where code = c);
  end loop;
  insert into rooms(code, data) values (c, jsonb_build_object('code', c, 'host', m.id, 'lang', coalesce(b->>'lang', 'en'), 'status', 'lobi',
    'players', jsonb_build_object(m.id::text, jsonb_build_object('nama', m.nama, 'score', 0)), 'questions', '[]'::jsonb, 'q', -1, 'q_start', 0,
    'answers', '{}'::jsonb, 'secs', 15, 'reveal_at', null, 'saved', false));
  return room_state(m, c);
end $$;

create or replace function tujlc.room_join(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare r jsonb; c text := upper(coalesce(b->>'code', ''));
begin
  select data into r from rooms where code = c for update;
  if r is null then perform err('Kode ruang tidak ditemukan.', 404); end if;
  if not (r->'players') ? m.id::text then
    if r->>'status' <> 'lobi' then perform err('Permainan sudah dimulai.'); end if;
    if (select count(*) from jsonb_object_keys(r->'players')) >= 5 then perform err('Ruang penuh (maksimal 5 pemain).'); end if;
    update rooms set data = jsonb_set(data, array['players', m.id::text], jsonb_build_object('nama', m.nama, 'score', 0)) where code = c;
  end if;
  return room_state(m, c);
end $$;

create or replace function tujlc.room_start(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare r jsonb; c text := upper(coalesce(b->>'code', '')); qs jsonb := coalesce(b->'questions', '[]'); clean jsonb;
begin
  select data into r from rooms where code = c for update;
  if r is null or (r->>'host') <> m.id::text then perform err('Hanya pembuat ruang yang bisa memulai.', 403); end if;
  if (select count(*) from jsonb_object_keys(r->'players')) < 2 then perform err('Butuh minimal 2 pemain.'); end if;
  if jsonb_typeof(qs) <> 'array' or jsonb_array_length(qs) not between 3 and 20 then perform err('Soal tidak valid.'); end if;
  begin
    select jsonb_agg(jsonb_build_object('p', left(q->>'p', 200), 'r', left(coalesce(q->>'r', ''), 120),
             'o', (select jsonb_agg(left(o, 120)) from (select jsonb_array_elements_text(q->'o') o limit 4) z), 'c', (q->>'c')::int) order by ord)
      into clean from jsonb_array_elements(qs) with ordinality as t(q, ord);
  exception when others then perform err('Soal tidak valid.');
  end;
  update rooms set data = data || jsonb_build_object('questions', clean, 'status', 'main', 'q', 0, 'q_start', epoch(), 'answers', '{}'::jsonb, 'reveal_at', null)
   where code = c;
  return room_state(m, c);
end $$;

create or replace function tujlc.room_answer(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare r jsonb; c text := upper(coalesce(b->>'code', '')); mid text := m.id::text; q jsonb; choice int; elapsed double precision; ok boolean; pts int;
begin
  select data into r from rooms where code = c for update;
  if r is null or not (r->'players') ? mid or r->>'status' <> 'main' or (r->'reveal_at' is not null and r->'reveal_at' <> 'null'::jsonb) then
    perform err('Tidak bisa menjawab sekarang.');
  end if;
  if (r->'answers') ? mid then return room_state(m, c); end if;
  begin choice := (b->>'choice')::int; exception when others then choice := -1; end;
  q := r->'questions'->((r->>'q')::int);
  elapsed := epoch() - (r->>'q_start')::double precision;
  ok := choice = (q->>'c')::int;
  pts := case when ok then floor(100 + greatest(0, (r->>'secs')::int - elapsed) * 10)::int else 0 end;
  r := jsonb_set(r, array['answers', mid], jsonb_build_object('choice', choice, 'ok', ok, 'pts', pts));
  r := jsonb_set(r, array['players', mid, 'score'], to_jsonb((r->'players'->mid->>'score')::int + pts));
  update rooms set data = r where code = c;
  return room_state(m, c);
end $$;

