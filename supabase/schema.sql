create or replace function tujlc.admin_cols(tbl text) returns text[] language sql immutable as $$
  select case tbl
    when 'events' then array['judul', 'tanggal', 'jam_mulai', 'jam_selesai', 'kampus', 'ruang', 'bahasa', 'deskripsi', 'kode_absen', 'tampil']
    when 'keuangan' then array['tanggal', 'jenis', 'kategori', 'uraian', 'nominal', 'bukti', 'event_id']
    when 'kelas_daftar' then array['status', 'level', 'kampus', 'jadwal', 'catatan']
    when 'pinjam_ruang' then array['kampus', 'ruang', 'tanggal', 'jam_mulai', 'jam_selesai', 'keperluan', 'event_id', 'pic', 'status', 'catatan']
    when 'periode' then array['nama', 'mulai', 'selesai', 'catatan', 'aktif']
    when 'pengurus' then array['nama', 'nim', 'jabatan', 'divisi', 'periode', 'urut']
    when 'members' then array['nama', 'role', 'aktif']
  end
$$;

create or replace function tujlc.admin_list(tbl text) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  return jsonb_build_object('rows', case tbl
    when 'members' then q_rows('select id, no_anggota, nama, email, nim, gender, tahun_lahir, role, aktif, created from members
                              where email not like ''%@demo.tujlc'' order by id')
    when 'kelas_daftar' then q_rows('select k.*, m.nama, m.nim from kelas_daftar k join members m on m.id = k.member_id order by k.id desc')
    when 'keuangan' then q_rows('select * from keuangan order by tanggal, id')
    when 'events' then q_rows('select e.*, (select count(*) from absensi a where a.event_id = e.id and a.status = ''hadir'') as hadir
                             from events e order by tanggal desc')
    when 'pengurus' then q_rows('select p.id, p.member_id, p.nama, p.nim, p.jabatan, p.divisi, p.periode, coalesce(f.data, p.foto) as foto, p.urut
                               from pengurus p left join fotos f on f.key = p.foto order by p.urut, p.nama')
    when 'pinjam_ruang' then q_rows('select * from pinjam_ruang order by id desc')
    when 'periode' then q_rows('select * from periode order by id desc')
  end);
end $$;

create or replace function tujlc.admin_save(tbl text, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare allowed text[] := admin_cols(tbl); cols text[]; b2 jsonb; new_id bigint; v_id bigint := nullif(b->>'id', '')::bigint;
begin
  if allowed is null then perform err('Tabel tidak dikenal.', 404); end if;
  -- "" dari formulir dianggap kosong (null) supaya kolom angka tidak error
  select coalesce(jsonb_object_agg(key, case when value = '""'::jsonb then 'null'::jsonb else value end), '{}') into b2 from jsonb_each(b);
  if tbl = 'events' and v_id is null and coalesce(b2->>'kode_absen', '') = '' then
    b2 := b2 || jsonb_build_object('kode_absen', tujlc.rand('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', 5));
  end if;
  if tbl = 'keuangan' and b2 ? 'nominal' then b2 := b2 || jsonb_build_object('nominal', coalesce(round((b2->>'nominal')::numeric), 0)); end if;
  select array_agg(k) into cols from jsonb_object_keys(b2) k where k = any(allowed);
  if tbl = 'periode' and coalesce(b2->>'aktif', '0') not in ('0', 'false') then update periode set aktif = 0; end if;
  if v_id is not null then
    if cols is null then return '{"ok": true}'; end if;
    execute format('update tujlc.%I t set %s from jsonb_populate_record(null::tujlc.%I, $1) r where t.id = $2', tbl,
                   (select string_agg(format('%I = r.%I', c, c), ', ') from unnest(cols) c), tbl) using b2, v_id;
    return jsonb_build_object('ok', true, 'id', v_id);
  end if;
  if tbl = 'members' then perform err('Anggota baru harus mendaftar sendiri.'); end if;
  if cols is null then perform err('Data kosong.'); end if;
  execute format('insert into tujlc.%I (%s) select %s from jsonb_populate_record(null::tujlc.%I, $1) returning id', tbl,
                 (select string_agg(quote_ident(c), ', ') from unnest(cols) c), (select string_agg(quote_ident(c), ', ') from unnest(cols) c), tbl)
    using b2 into new_id;
  return jsonb_build_object('ok', true, 'id', new_id);
end $$;

create or replace function tujlc.admin_delete(tbl text, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare v_id bigint := (b->>'id')::bigint;
begin
  if admin_cols(tbl) is null or tbl = 'members' then perform err('Tidak bisa dihapus.'); end if;
  if tbl = 'keuangan' then update iuran set status = 'belum' where id = (select iuran_id from keuangan where id = v_id); end if;
  if tbl = 'pengurus' then delete from fotos where key like 'upload/%' and key = (select foto from pengurus where id = v_id); end if;
  execute format('delete from tujlc.%I where id = $1', tbl) using v_id;
  return '{"ok": true}';
end $$;

create or replace function tujlc.iuran_bulan(bulan text) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  return jsonb_build_object('rows', q_rows(
    'select m.id as member_id, m.nama, m.nim, m.no_anggota, coalesce(i.status, ''belum'') as status, i.nominal, i.tanggal
       from members m left join iuran i on i.member_id = m.id and i.bulan = $1[1]
      where m.aktif = 1 and m.email not like ''%@demo.tujlc'' order by m.nama', coalesce(bulan, '')));
end $$;

create or replace function tujlc.iuran_set(b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare v_mid bigint := (b->>'member_id')::bigint; v_bulan text := b->>'bulan'; v_lunas boolean := coalesce(b->>'lunas', 'false') in ('true', '1');
        v_nom bigint; v_nama text; v_old bigint; v_iid bigint;
begin
  v_nom := coalesce(nullif(b->>'nominal', '')::bigint, setting('iuran_nominal')::bigint, 10000);
  select nama into v_nama from members where id = v_mid;
  if v_nama is null then perform err('Anggota tidak ditemukan.', 404); end if;
  select id into v_old from iuran where member_id = v_mid and bulan = v_bulan;
  if v_old is not null then delete from keuangan where iuran_id = v_old; end if;
  insert into iuran(member_id, bulan, nominal, status, tanggal) values (v_mid, v_bulan, v_nom, case when v_lunas then 'lunas' else 'belum' end, today())
    on conflict (member_id, bulan) do update set status = excluded.status, nominal = excluded.nominal, tanggal = excluded.tanggal
    returning id into v_iid;
  if v_lunas then  -- otomatis masuk buku kas
    insert into keuangan(tanggal, jenis, kategori, uraian, nominal, iuran_id)
      values (today(), 'masuk', 'Iuran kas', format('Iuran kas %s – %s', v_bulan, v_nama), v_nom, v_iid);
  end if;
  return '{"ok": true}';
end $$;

create or replace function tujlc.absensi_event(eid bigint) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  return jsonb_build_object('rows', q_rows(
    'select m.id as member_id, m.nama, m.nim, coalesce(a.status, '''') as status, a.waktu from members m
       left join absensi a on a.member_id = m.id and a.event_id = $1[1]::bigint
      where m.aktif = 1 and m.email not like ''%@demo.tujlc'' order by m.nama', coalesce(eid, 0)::text));
end $$;

create or replace function tujlc.absensi_set(b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  if coalesce(b->>'status', '') = '' then
    delete from absensi where event_id = (b->>'event_id')::bigint and member_id = (b->>'member_id')::bigint;
  else
    insert into absensi(event_id, member_id, status, waktu) values ((b->>'event_id')::bigint, (b->>'member_id')::bigint, b->>'status', now_iso())
      on conflict (event_id, member_id) do update set status = excluded.status;
  end if;
  return '{"ok": true}';
end $$;

create or replace function tujlc.summary() returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare masuk bigint; keluar bigint; bln text := left(today(), 7); ang bigint; lunas bigint;
begin
  select coalesce(sum(nominal), 0) into masuk from keuangan where jenis = 'masuk';
  select coalesce(sum(nominal), 0) into keluar from keuangan where jenis = 'keluar';
  select count(*) into ang from members where aktif = 1 and email not like '%@demo.tujlc';
  select count(*) into lunas from iuran where bulan = bln and status = 'lunas';
  return jsonb_build_object('saldo', masuk - keluar, 'masuk', masuk, 'keluar', keluar, 'anggota', ang,
    'pengurus', (select count(*) from members where role = 'pengurus' and email not like '%@demo.tujlc'),
    'bulan', bln, 'iuran_lunas', lunas, 'iuran_belum', ang - lunas,
    'event_mendatang', (select count(*) from events where tanggal >= today()),
    'kelas_menunggu', (select count(*) from kelas_daftar where status = 'menunggu'),
    'pinjam_rencana', (select count(*) from pinjam_ruang where status in ('rencana', 'diajukan')),
    'kode_pengurus', setting('kode_pengurus'), 'iuran_nominal', coalesce(setting('iuran_nominal')::int, 10000), 'kampus', kampus());
end $$;

create or replace function tujlc.settings_save(b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
begin
  if coalesce(b->>'regen_kode', '0') not in ('0', 'false') then
    insert into settings values ('kode_pengurus', 'PGR-' || tujlc.rand('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789', 6))
      on conflict (k) do update set v = excluded.v;
  end if;
  if coalesce(b->>'iuran_nominal', '') <> '' then
    insert into settings values ('iuran_nominal', round((b->>'iuran_nominal')::numeric)::bigint::text) on conflict (k) do update set v = excluded.v;
  end if;
  return summary();
end $$;

create or replace function tujlc.reset_member_code(b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare v_kode text := new_member_code(); v_id bigint := (b->>'id')::bigint;
begin
  update members set kode_hash = hash_code(v_kode) where id = v_id;
  delete from sessions where member_id = v_id;
  return jsonb_build_object('kode', v_kode);
end $$;

