-- ---------------------------------------------------------------------
-- Satu-satunya pintu dari browser
--   p_path : sama seperti alamat server Python dulu, mis. "/api/home", "/api/admin/events"
--   p_q    : parameter ?query (GET)
--   p_body : isi POST; null berarti GET
-- ---------------------------------------------------------------------
create or replace function public.tujlc_api(p_token text default null, p_path text default '', p_q jsonb default '{}', p_body jsonb default null)
returns jsonb language plpgsql security definer set search_path = tujlc, extensions, public as $$
declare
  path text := regexp_replace(coalesce(p_path, ''), '^/?(api/)?', '');
  q jsonb := coalesce(p_q, '{}');
  b jsonb := coalesce(p_body, '{}');
  is_get boolean := p_body is null;
  m tujlc.members;
  part text;
begin
  if path = 'register' then return tujlc.register(b); end if;
  if path = 'login' then return tujlc.login(b); end if;
  if path = 'demo' then return tujlc.demo_login(coalesce(b->>'role', 'anggota')); end if;
  if path = 'logout' then delete from tujlc.sessions where token = p_token; return '{"ok": true}'; end if;

  -- Impor foto lama (dipakai sekali oleh tools/supabase_upload_foto.py), dijaga kode pengurus
  if path = 'setup/foto' then
    if upper(btrim(coalesce(b->>'kode_pengurus', ''))) is distinct from tujlc.setting('kode_pengurus') then perform tujlc.err('Kode pengurus salah.', 403); end if;
    if coalesce(b->>'key', '') !~ '^(pengurus|galeri)/[a-z0-9_-]+$' or coalesce(b->>'data', '') not like 'data:image/%' then perform tujlc.err('Data foto tidak valid.'); end if;
    insert into tujlc.fotos values (b->>'key', b->>'data') on conflict (key) do update set data = excluded.data;
    return '{"ok": true}';
  end if;

  select mm.* into m from tujlc.sessions s join tujlc.members mm on mm.id = s.member_id
   where s.token = p_token and s.exp > now() and mm.aktif = 1;
  if path = 'me' then return jsonb_build_object('me', case when m.id is null then null else tujlc.public_member(m) end); end if;
  if m.id is null then perform tujlc.err('Silakan masuk sebagai anggota.', 401); end if;

  case path
    when 'home' then return tujlc.member_home(m);
    when 'galeri' then return jsonb_build_object('fotos', coalesce((select jsonb_agg(data order by key) from tujlc.fotos where key like 'galeri/%'), '[]'));
    when 'leaderboard' then return tujlc.leaderboard(q->>'game', q->>'lang');
    when 'room/state' then return tujlc.room_state(m, q->>'code');
    when 'pengurus/daftar' then return tujlc.register_pengurus(m, b);
    when 'kelas' then return tujlc.daftar_kelas(m, b);
    when 'absen' then return tujlc.absen_mandiri(m, b);
    when 'score' then return tujlc.add_score(m.id, b);
    when 'room/create' then return tujlc.room_create(m, b);
    when 'room/join' then return tujlc.room_join(m, b);
    when 'room/start' then return tujlc.room_start(m, b);
    when 'room/answer' then return tujlc.room_answer(m, b);
    else null;
  end case;

  if path like 'admin/%' then
    if m.role <> 'pengurus' then perform tujlc.err('Khusus pengurus.', 403); end if;
    part := substr(path, 7);
    if part = 'summary' then return tujlc.summary(); end if;
    if part = 'dump' then return tujlc.admin_dump(); end if;
    if part = 'iuran' then return case when is_get then tujlc.iuran_bulan(q->>'bulan') else tujlc.iuran_set(b) end; end if;
    if part = 'absensi' then return case when is_get then tujlc.absensi_event(nullif(q->>'event', '')::bigint) else tujlc.absensi_set(b) end; end if;
    if part = 'settings' then return tujlc.settings_save(b); end if;
    if part = 'reset-kode' then return tujlc.reset_member_code(b); end if;
    if part like '%/delete' then return tujlc.admin_delete(left(part, -7), b); end if;
    if is_get then return tujlc.admin_list(part); end if;
    return tujlc.admin_save(part, b);
  end if;
  perform tujlc.err('Tidak ditemukan.', 404);
end $$;

revoke all on all functions in schema tujlc from public, anon, authenticated;
revoke all on function public.tujlc_api(text, text, jsonb, jsonb) from public;
grant execute on function public.tujlc_api(text, text, jsonb, jsonb) to anon, authenticated;
