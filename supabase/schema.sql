create or replace function tujlc.register(b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare
  v_nama text := btrim(coalesce(b->>'nama', ''));
  v_email text := lower(btrim(coalesce(b->>'email', '')));
  v_nim text := regexp_replace(coalesce(b->>'nim', ''), '\D', '', 'g');
  v_gender text := b->>'gender';
  v_tahun int; v_kode text; v_no text; n int;
  yr int := extract(year from now() at time zone 'Asia/Jakarta');
begin
  begin v_tahun := (b->>'tahun_lahir')::int; exception when others then v_tahun := 0; end;
  if length(v_nama) < 3 then perform err('Nama minimal 3 huruf.'); end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then perform err('Email tidak valid.'); end if;
  if length(v_nim) not between 8 and 15 then perform err('NIM harus 8–15 digit angka.'); end if;
  if coalesce(v_gender, '') not in ('Laki-laki', 'Perempuan') then perform err('Pilih gender.'); end if;
  if coalesce(v_tahun, 0) not between 1970 and yr - 14 then perform err('Tahun lahir tidak valid.'); end if;
  if coalesce(b->>'setuju', 'false') not in ('true', '1') then perform err('Centang persetujuan penggunaan data.'); end if;
  lock table members in share row exclusive mode;
  if exists (select 1 from members where email = v_email or nim = v_nim) then
    perform err('Email atau NIM sudah terdaftar. Masuk dengan kode yang pernah kamu dapat.', 409);
  end if;
  select count(*) + 1 into n from members where email not like '%@demo.tujlc';
  v_no := format('TUJLC-%s-%s', yr, lpad(n::text, 4, '0'));
  v_kode := new_member_code();
  insert into members(no_anggota, nama, email, nim, gender, tahun_lahir, kode_hash, created)
    values (v_no, v_nama, v_email, v_nim, v_gender, v_tahun, hash_code(v_kode), now_iso());
  return jsonb_build_object('kode', v_kode, 'no_anggota', v_no, 'nama', v_nama);
end $$;

create or replace function tujlc.new_session(mid bigint, days int) returns text
language plpgsql set search_path = tujlc, extensions, public as $$
declare tok text := encode(extensions.gen_random_bytes(32), 'hex');
begin
  delete from sessions where exp < now();
  insert into sessions values (tok, mid, now() + make_interval(days => days));
  return tok;
end $$;

create or replace function tujlc.login(b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare who text := lower(btrim(coalesce(b->>'nim', ''))); v_kode text := upper(btrim(coalesce(b->>'kode', ''))); m members;
begin
  select * into m from members
   where (nim = nullif(regexp_replace(who, '\D', '', 'g'), '') or email = who) and aktif = 1 limit 1;
  if m.id is null or m.kode_hash is null or m.kode_hash <> extensions.crypt(v_kode, m.kode_hash) then
    perform pg_sleep(0.6);
    perform err('NIM/email atau kode anggota salah.', 401);
  end if;
  return jsonb_build_object('token', new_session(m.id, 30), 'me', public_member(m));
end $$;

create or replace function tujlc.demo_login(role text) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare m members;
begin
  -- Versi online: tamu pengurus dimatikan supaya data pribadi anggota tidak bisa dibuka siapa saja.
  if role = 'pengurus' then perform err('Tamu pengurus hanya bisa dipakai di laptop server, tidak di web online.', 403); end if;
  if role is distinct from 'anggota' then perform err('Peran tamu tidak dikenal.'); end if;
  select * into m from members where email = 'demo-anggota@demo.tujlc';
  if m.id is null then
    insert into members(no_anggota, nama, email, nim, gender, tahun_lahir, kode_hash, role, created)
      values ('DEMO-ANGGOTA', 'Tamu Anggota', 'demo-anggota@demo.tujlc', '0000000001', 'Laki-laki', 2005,
              hash_code(encode(extensions.gen_random_bytes(8), 'hex')), 'anggota', now_iso())
      returning * into m;
  end if;
  return jsonb_build_object('token', new_session(m.id, 1), 'me', public_member(m) || '{"demo": true}');
end $$;

create or replace function tujlc.register_pengurus(m tujlc.members, b jsonb) returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare v_jab text := btrim(coalesce(b->>'jabatan', '')); v_div text := btrim(coalesce(b->>'divisi', ''));
        v_per text := btrim(coalesce(b->>'periode', '')); v_foto text := coalesce(b->>'foto', ''); v_key text;
begin
  if upper(btrim(coalesce(b->>'kode_pengurus', ''))) is distinct from setting('kode_pengurus') then
    perform err('Kode pengurus salah. Minta ke Ketua/Sekretaris.', 403);
  end if;
  if v_jab = '' or v_per = '' then perform err('Isi jabatan dan periode.'); end if;
  if v_foto not like 'data:image/%' then perform err('Unggah foto formal.'); end if;
  if length(v_foto) > 4200000 then perform err('Foto maksimal 3 MB.'); end if;
  v_key := 'upload/m' || m.id || '-' || tujlc.rand('abcdef0123456789', 8);
  insert into fotos values (v_key, v_foto);
  update members set role = 'pengurus' where id = m.id;
  delete from fotos where key in (select foto from pengurus where member_id = m.id and periode = v_per);
  delete from pengurus where member_id = m.id and periode = v_per;
  insert into pengurus(member_id, nama, nim, jabatan, divisi, periode, foto, urut)
    values (m.id, m.nama, m.nim, v_jab, v_div, v_per, v_key, case when lower(v_jab) like '%ketua%' then 5 else 30 end);
  if not exists (select 1 from periode where nama = v_per) then
    insert into periode(nama, catatan, aktif) values (v_per, 'Dibuat otomatis saat pendaftaran pengurus', 0);
  end if;
  return '{"ok": true}';
end $$;

