create or replace function tujlc.err(msg text, code int default 400) returns void
language plpgsql set search_path = tujlc, extensions, public as $$
begin raise exception using message = msg, detail = code::text; end $$;

create or replace function tujlc.today() returns text language sql stable as
$$ select to_char(now() at time zone 'Asia/Jakarta', 'YYYY-MM-DD') $$;

create or replace function tujlc.now_iso() returns text language sql stable as
$$ select to_char(now() at time zone 'Asia/Jakarta', 'YYYY-MM-DD"T"HH24:MI:SS') $$;

create or replace function tujlc.epoch() returns double precision language sql volatile as
$$ select extract(epoch from clock_timestamp())::double precision $$;

create or replace function tujlc.rand(chars text, n int) returns text
language plpgsql volatile set search_path = tujlc, extensions, public as $$
declare b bytea := extensions.gen_random_bytes(n); s text := '';
begin
  for i in 0..n - 1 loop s := s || substr(chars, 1 + get_byte(b, i) % length(chars), 1); end loop;
  return s;
end $$;

create or replace function tujlc.setting(key text) returns text language sql stable as
$$ select v from tujlc.settings where k = key $$;

create or replace function tujlc.q_rows(sql text, variadic args text[] default '{}') returns jsonb
language plpgsql set search_path = tujlc, extensions, public as $$
declare out jsonb;
begin
  execute format('select coalesce(jsonb_agg(to_jsonb(x)), ''[]''::jsonb) from (%s) x', sql) into out using args;
  return out;
end $$;

