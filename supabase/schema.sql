create extension if not exists pgcrypto with schema extensions;
create schema if not exists tujlc;
revoke all on schema tujlc from public, anon, authenticated;

create table if not exists tujlc.members(
  id bigint generated by default as identity primary key, no_anggota text unique, nama text, email text unique, nim text unique,
  gender text, tahun_lahir int, kode_hash text, role text default 'anggota', aktif int default 1, created text);
create table if not exists tujlc.sessions(token text primary key, member_id bigint references tujlc.members(id) on delete cascade, exp timestamptz);
create table if not exists tujlc.settings(k text primary key, v text);
create table if not exists tujlc.periode(id bigint generated by default as identity primary key, nama text, mulai text, selesai text, catatan text, aktif int default 0);
create table if not exists tujlc.pengurus(id bigint generated by default as identity primary key, member_id bigint, nama text, nim text,
  jabatan text, divisi text, periode text, foto text, urut int default 50);
create table if not exists tujlc.events(id bigint generated by default as identity primary key, judul text, tanggal text, jam_mulai text, jam_selesai text,
  kampus text, ruang text, bahasa text, deskripsi text, kode_absen text, tampil int default 1);
create table if not exists tujlc.absensi(id bigint generated by default as identity primary key, event_id bigint, member_id bigint, status text, waktu text,
  unique(event_id, member_id));
create table if not exists tujlc.keuangan(id bigint generated by default as identity primary key, tanggal text, jenis text, kategori text, uraian text,
  nominal bigint, bukti text, event_id bigint, iuran_id bigint);
create table if not exists tujlc.iuran(id bigint generated by default as identity primary key, member_id bigint, bulan text, nominal bigint, status text,
  tanggal text, unique(member_id, bulan));
create table if not exists tujlc.kelas_daftar(id bigint generated by default as identity primary key, member_id bigint, bahasa text, level text, kampus text,
  jadwal text, catatan text, status text default 'menunggu', created text);
create table if not exists tujlc.pinjam_ruang(id bigint generated by default as identity primary key, kampus text, ruang text, tanggal text, jam_mulai text,
  jam_selesai text, keperluan text, event_id bigint, pic text, status text default 'rencana', catatan text);
create table if not exists tujlc.scores(id bigint generated by default as identity primary key, member_id bigint, game text, lang text, score int, created text);
create table if not exists tujlc.rooms(code text primary key, data jsonb, created timestamptz default now());
-- Foto privat (pengurus, galeri anggota, unggahan) disimpan sebagai data URL, hanya keluar lewat tujlc_api untuk yang sudah login.
create table if not exists tujlc.fotos(key text primary key, data text);

